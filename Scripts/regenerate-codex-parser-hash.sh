#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE_DIR="${ROOT_DIR}/Sources/CodexBarCore/Vendored/CostUsage"
OUTPUT_FILE="${ROOT_DIR}/Sources/CodexBarCore/Generated/CodexParserHash.generated.swift"
STORE_FILE="${ROOT_DIR}/Sources/CodexBarCore/Vendored/CostUsage/CostUsageStore.swift"
MODE="write"
SEMANTIC_CHANGE=0

for argument in "$@"; do
  case "$argument" in
    write | --write)
      MODE="write"
      ;;
    check | --check)
      MODE="check"
      ;;
    --semantic-change)
      # Declares that Codex row semantics changed, so existing caches must rebuild from session files.
      SEMANTIC_CHANGE=1
      ;;
    *)
      echo "Usage: $0 [write|--write|check|--check] [--semantic-change]" >&2
      exit 2
      ;;
  esac
done

if [[ "$MODE" == "check" ]]; then
  CHECK_ONLY=1
else
  CHECK_ONLY=0
fi

if command -v shasum >/dev/null 2>&1; then
  HASH_CMD=(shasum -a 256)
elif command -v sha256sum >/dev/null 2>&1; then
  HASH_CMD=(sha256sum)
else
  echo "error: shasum or sha256sum is required" >&2
  exit 1
fi

FILE_LIST="$(mktemp)"
trap 'rm -f "$FILE_LIST"' EXIT

# Storage-only files have their own schema-version gate and do not change parser semantics.
find "$SOURCE_DIR" \
  -type f \
  -name '*.swift' \
  ! -name '*Claude*' \
  ! -name 'CostUsageStore*.swift' \
  -print |
  sed "s#^${ROOT_DIR}/##" |
  LC_ALL=C sort >"$FILE_LIST"

HASH="$(
  while IFS= read -r file; do
    printf '== %s ==\n' "$file"
    cat "${ROOT_DIR}/${file}"
    printf '\n'
  done <"$FILE_LIST" | "${HASH_CMD[@]}"
)"
HASH="${HASH%% *}"
SHORT_HASH="${HASH:0:16}"

# The hash committed in the generated file, i.e. the parser identity that existing user caches carry.
committed_hash() {
  [[ -f "$OUTPUT_FILE" ]] || return 0
  sed -n 's/^[[:space:]]*static let value = "\([0-9a-f]*\)".*$/\1/p' "$OUTPUT_FILE" | head -n 1
}

# Hashes CostUsageStore adopts without wiping the user's cache (compatiblePredecessorParserHashes).
predecessor_hashes() {
  [[ -f "$STORE_FILE" ]] || return 0
  awk '
    /static let compatiblePredecessorParserHashes/ { inside = 1; next }
    inside && /^[[:space:]]*\]/ { exit }
    inside { print }
  ' "$STORE_FILE" | grep -oE '"[0-9a-f]{16}"' | tr -d '"'
}

# Every parser hash change wipes and rebuilds each Codex cost cache unless the previous hash is adopted.
# Refuse to publish a new hash until the previous one is listed or the rebuild is declared intentional.
require_adopted_predecessor() {
  local previous="$1"
  [[ -n "$previous" && "$previous" != "$SHORT_HASH" ]] || return 0
  if predecessor_hashes | grep -qx "$previous"; then
    return 0
  fi
  if [[ "$SEMANTIC_CHANGE" -eq 1 ]]; then
    echo "warning: Codex parser hash ${previous} -> ${SHORT_HASH} is declared a semantic change; existing Codex cost caches will rebuild." >&2
    return 0
  fi
  cat >&2 <<MESSAGE
error: Codex parser hash changes from ${previous} to ${SHORT_HASH}, but ${previous} is not in
CostUsageStore.compatiblePredecessorParserHashes. Every user's Codex cost cache would be wiped and rescanned.
If Codex row parsing is unchanged, add "${previous}" (with a comment) to compatiblePredecessorParserHashes in
${STORE_FILE#${ROOT_DIR}/} and rerun this script. If Codex row semantics really changed, rerun with --semantic-change.
MESSAGE
  return 1
}

render_generated() {
  cat <<SWIFT
// Generated by Scripts/regenerate-codex-parser-hash.sh. Do not edit by hand.

enum CodexParserHash {
    static let value = "$SHORT_HASH"
}
SWIFT
}

if [[ "$CHECK_ONLY" -eq 1 ]]; then
  EXPECTED_FILE="$(mktemp)"
  trap 'rm -f "$FILE_LIST" "$EXPECTED_FILE"' EXIT
  render_generated >"$EXPECTED_FILE"
  if ! cmp -s "$EXPECTED_FILE" "$OUTPUT_FILE"; then
    require_adopted_predecessor "$(committed_hash)" || true
    echo "error: ${OUTPUT_FILE#${ROOT_DIR}/} is stale. Run Scripts/regenerate-codex-parser-hash.sh and commit the result." >&2
    if [[ -f "$OUTPUT_FILE" ]]; then
      diff -u "$OUTPUT_FILE" "$EXPECTED_FILE" >&2 || true
    else
      diff -u /dev/null "$EXPECTED_FILE" >&2 || true
    fi
    exit 1
  fi
  echo "Codex parser hash is current (${SHORT_HASH})"
  exit 0
fi

require_adopted_predecessor "$(committed_hash)" || exit 1

mkdir -p "$(dirname "$OUTPUT_FILE")"
render_generated >"$OUTPUT_FILE"

echo "Updated ${OUTPUT_FILE#${ROOT_DIR}/} to ${SHORT_HASH}"
