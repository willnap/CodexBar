#!/usr/bin/env python3
"""Bake production catalogue packing solutions with current system SF glyphs, without opening a window."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Sources/CodexBar/NativeGauge"
OUTPUT = SOURCE / "Generated/NativeOrbitWarningCatalogueLayoutsData.swift"


def block(text, declaration):
    start = text.index(declaration)
    brace = text.index("{", start)
    depth, end = 1, brace + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[start:end]


def generate(output):
    warnings = (SOURCE / "NativeOrbitWarningLight.swift").read_text()
    hdr = (SOURCE / "NativeOrbitWarningHDRView.swift").read_text()
    symbol = (SOURCE / "NativeOrbitSymbol.swift").read_text()
    money = (SOURCE / "NativeOrbitMoneyReading.swift").read_text()
    constants = [line.replace("nonisolated ", "") for line in symbol.splitlines()
                 if "static let radii:" in line or "static let stroke:" in line]
    parts = [
        "import AppKit",
        "struct NativeOrbitWarningLight {" + block(warnings, "enum Kind:")
        + "\n" + block(warnings, "enum Severity:") + "}",
        block(hdr, "enum NativeOrbitWarningHDRColor:"),
        block(hdr, "struct NativeOrbitWarningHDRItem:"),
        "@MainActor\n" + block(hdr, "enum NativeOrbitWarningHDRRaster {"),
        "struct NativeOrbitSymbol {\n" + "\n".join(constants) + "\n}",
        "struct NativeOrbitMoneyReading {" + block(money, "static func size(lanes:") + "}",
        "enum NativeOrbitWarningCatalogueLayouts { static func positions(for key: String, "
        "bounds: [CGRect], symbolScale: CGFloat) -> [CGPoint]? { nil } }",
        "struct NativeOrbitWarningHDRView { @MainActor static func symbolSize(_ symbol: String) -> CGSize {"
        "NativeOrbitWarningHDRRaster.symbolImage(symbol)?.size ?? .zero } }",
    ]
    for name in ["NativeOrbitWarningBulbPositions", "NativeOrbitWarningLayout", "NativeOrbitWarningInk"]:
        text = (SOURCE / f"{name}.swift").read_text()
        text = text.replace("private static func canonicalReservation", "static func canonicalReservation")
        text = text.replace("private static func layoutKey", "static func layoutKey")
        parts.append(text)
    parts.append((ROOT / "Scripts/WarningCatalogue/Generate.swift").read_text())
    with tempfile.TemporaryDirectory(prefix="codexbar-warning-catalogue-") as directory:
        temp = Path(directory)
        (temp / "Generate.swift").write_text("\n".join(parts))
        subprocess.run(["swiftc", "-O", "-parse-as-library", str(temp / "Generate.swift"),
                        "-o", str(temp / "generate")], check=True)
        subprocess.run([str(temp / "generate"), str(temp / "layouts.json")], check=True)
        data = json.loads((temp / "layouts.json").read_text())
    lines = ["import Foundation", "",
             "// Generated by Scripts/generate_warning_catalogue_layouts.py. Do not edit coordinates by hand.", "",
             "extension NativeOrbitWarningCatalogueLayouts {", "    static let inkBounds: [CGRect] = ["]
    for x, y, width, height in data["bounds"]:
        lines.append(f"        CGRect(x: {x}, y: {y}, width: {width}, height: {height}),")
    lines.extend(["    ]", "", "    static let coordinates: [String: [CGFloat]] = ["])
    for key, points in sorted(data["layouts"].items()):
        lines.append("        " + json.dumps(key) + ": [")
        for point in points:
            lines.extend(f"            {value}," for value in point)
        lines.append("        ],")
    lines.extend(["    ]", "}", ""])
    output.write_text("\n".join(lines))
    formatter = ROOT / ".build/lint-tools/bin/swiftformat"
    if formatter.exists():
        subprocess.run([str(formatter), str(output)], check=True)
    print(f"Saved {len(data['layouts'])} layouts to {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    generate(parser.parse_args().output)
